rows, name = [], None
for ln in cfg:
    s = ln.strip()
    if not s or s.startswith('#'):
        continue
    if s.startswith('[') and s.endswith(']'):
        continue
    if '#' in s:
        body, note = s.split('#', 1)
        key, name = body.strip(), note.strip().lstrip('★').strip()
    else:
        key, name = s, s
    rows.append((key, name))

# 用 profile 里的规范标题优先
KEY2TITLE = {p['key']: p.get('title') for p in sys_profiles if 'error' not in p}

out, missing = [], []
for key, name in rows:
    title = KEY2TITLE.get(key) or name
    # 逐个尝试匹配分类表
    hit = None
    for cand in (title, name):
        for k, v in C.items():
            if k == cand or k in cand or cand in k:
                hit = (k, v); break
        if hit: break
    prof = by_key.get(key, {})
    org_from_site = prof.get('author') or ''
    if hit:
        cname, (org, kind, risk, tip) = hit
        org = org or org_from_site
    else:
        missing.append((title, key))
        org, kind, risk, tip = (org_from_site or '待确认'), '待确认', '待确认', '尚未归类'
    role = kind
    kind = KIND_MAP.get(kind, "个人IP" if kind != "待确认" else "待确认")
    out.append({'key': key, 'title': title, 'org': org, 'author': org_from_site,
                'kind': kind, 'role': role, 'risk': risk, 'tip': tip,
                'subs': prof.get('subs') or ''})

with open(CLS / 'profiles.csv', 'w', encoding='utf-8', newline='') as f:
    w = csv.DictWriter(f, fieldnames=['key', 'title', 'org', 'author', 'kind', 'role', 'risk', 'tip', 'subs'])
    w.writeheader()
    w.writerows(out)

print(f"共 {len(out)} 档 | 已归类 {len(out) - len(missing)} | 待确认 {len(missing)}")
