def cell(s) -> str:
    """转义 Markdown 表格里的竖线，避免撑破单元格。"""
    return str(s).replace("|", "\\|")

L = ["# 播客背景与立场梳理", "",
     f"共 **{len(out)} 档**。分类依据优先取小宇宙页面的一手字段（`author` / `podcasters` 里的主播简介），",
     "其余走 RSS 通道、拿不到该字段的按公开信息补充。", "",
     "**为什么值得先分这一层**：VC 自营号本质是募资与被投企业的传播渠道，",
     "它给你的行业判断往往带有自身持仓视角；而独立媒体和一线从业者的内容，",
     "才更适合作为外部事实和认知的输入。两类都要读，但读法完全不同。", "",
     "## 性质总览", ""]
for k in ["机构自营", "独立媒体", "个人IP", "品牌播客", "二手工具号"]:
    n = sum(1 for r in out if r["kind"] == k)
    L.append(f"- **{k}**：{n} 档 —— {KIND_INTRO[k]}")
L.append("")

order = {"高": 0, "中": 1, "低": 2}
for k in ["机构自营", "独立媒体", "个人IP", "品牌播客", "二手工具号"]:
    g = [r for r in out if r["kind"] == k]
    if not g:
        continue
    g.sort(key=lambda r: (order.get(r["risk"], 9), -(int(r["subs"] or 0))))
    L += [f"## {k}（{len(g)} 档）", "", "| 播客 | 出品方 / 主播背景 | 立场 | 读法建议 |", "|---|---|---|---|"]
    for r in g:
        subs = f" · {int(r['subs'])} 订阅" if r["subs"] else ""
        L.append(f"| {cell(r['title'])} | {cell(r['org'])}{subs} | {r['risk']} | {cell(r['tip'])} |")
    L.append("")

hi = [r for r in out if r["risk"] == "高"]
L += ["## 最先要留意的：立场「高」的 11 档", "",
      "这些是机构的官方出口，读到具体公司案例、行业判断时，先问一句「这是谁的项目／谁的方法论」。", ""]
for r in hi:
    L.append(f"- **{r['title']}** —— {r['org']}")
L += ["", "## 对照：立场「低」、可作为独立信源先梳理的", ""]
lo = [r for r in out if r["risk"] == "低"]
for r in sorted(lo, key=lambda r: -(int(r["subs"] or 0)))[:20]:
    L.append(f"- **{r['title']}** —— {r['org']}")
L += ["", "---", "",
      "_注：性质与立场是按公开信息判断的，可能与主理人自述有出入；"
      "「读法建议」是给你做信息分诊用的，不代表内容质量好坏——"
      "机构自营号里也有大量一手信息，只是需要你知道它的立场在哪。_"]

